"""Bake the receipt frame, labels and numeral masks used by the Discord Worker."""
import base64
import json
from pathlib import Path
import zlib

from PIL import Image, ImageDraw, ImageFont

WIDTH, HEIGHT = 680, 224
OUT = Path(__file__).resolve().parents[2] / "server/discord/casino-receipt-art.js"
FONTS = Path("C:/Windows/Fonts")


def pack(data):
    return base64.b64encode(zlib.compress(data, 9)).decode("ascii")


def frame(label):
    image = Image.new("RGB", (WIDTH, HEIGHT), "#33212a")
    draw = ImageDraw.Draw(image)
    for x in range(-HEIGHT, WIDTH, 15):
        draw.line((x, 0, x + HEIGHT, HEIGHT), fill="#52362f")
    draw.rectangle((27, 27, 652, 196), fill="#24171d")
    draw.rounded_rectangle((12, 12, 667, 211), radius=8, outline="#ba8d61", width=2)
    draw.rectangle((25, 25, 654, 198), outline="#815641")
    for x, y, sx, sy in [(25, 25, 1, 1), (654, 25, -1, 1), (25, 198, 1, -1), (654, 198, -1, -1)]:
        def corner(points):
            return [(x + px * sx, y + py * sy) for px, py in points]

        draw.line(corner([(0, 31), (5, 18), (11, 11), (18, 5), (31, 0)]), fill="#d3a575", width=2)
        draw.polygon(corner([(12, 7), (17, 12), (12, 17), (7, 12)]), fill="#d3a575")
    for y in range(48, 176, 9):
        draw.line((450, y, 450, y + 3), fill="#85614c")
    font = ImageFont.truetype(str(FONTS / "msjhbd.ttc"), 26)
    for point, text in [((57, 72), label), ((482, 72), "遊玩局數"), ((57, 173), "戲籌"), ((482, 173), "局")]:
        draw.text(point, text, font=font, fill="#ecd8bf", anchor="lm")
    return pack(image.tobytes())


font = ImageFont.truetype(str(FONTS / "georgiab.ttf"), 64)
glyphs = {}
for char in "0123456789,+−":
    advance = round(font.getlength(char)) + 1
    image = Image.new("L", (advance, 76))
    ImageDraw.Draw(image).text((0, 57), char, font=font, fill=255, anchor="ls")
    glyphs[char] = [advance, pack(image.tobytes())]

frames = {key: frame(label) for key, label in [("gain", "本次淨贏"), ("loss", "本次淨輸"), ("even", "本次打平")]}
OUT.write_text(
    "// Generated by scripts/assets/build-casino-receipt.py.\n"
    f"export const receiptFrames = {json.dumps(frames, ensure_ascii=False)};\n"
    f"export const receiptGlyphs = {json.dumps(glyphs, ensure_ascii=False)};\n",
    encoding="utf-8",
)
