"""Bake the original dealer art and font masks for Discord jackpot cards."""
import base64
import json
from pathlib import Path
import zlib

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = Path('C:/Windows/Fonts')
OUT = ROOT / 'server/discord/discord-win-card-art.js'
ART = json.loads((ROOT / 'docs/data/announcement-art.json').read_text(encoding='utf-8'))
COLORS = {'big': '#efc08e', 'super': '#fff0b9', 'mega': '#ff9fb7'}
BG = '#2d2428'


def pack(data):
    return base64.b64encode(zlib.compress(data, 9)).decode('ascii')


def masks(font, font_size):
    result = {}
    for char in '0123456789,.×':
        advance = round(font.getlength(char)) + 1
        image = Image.new('L', (advance, font_size + 12))
        ImageDraw.Draw(image).text((0, font_size), char, font=font, fill=255, anchor='ls')
        result[char] = [advance, pack(image.tobytes())]
    return result


def build(record):
    tier = record['tier']
    compact = tier == 'big'
    width = 552 if compact else 720
    font_size = 40 if compact else 49
    font = ImageFont.truetype(str(FONTS / 'georgiab.ttf'), font_size)
    label = ImageFont.truetype(str(FONTS / 'msjh.ttc'), 21 if compact else 24)
    with Image.open(ROOT / record['file']) as original:
        art_width = 112 if compact else width - 36
        art_height = round(original.height * art_width / original.width)
        artwork = original.convert('RGB').resize((art_width, art_height), Image.Resampling.LANCZOS)
    art_x, art_y = (width - art_width - 18, 18) if compact else (18, 119)
    height = art_y + art_height + 18
    frame = Image.new('RGB', (width, height), BG)
    draw = ImageDraw.Draw(frame)
    # Keep the art uncropped, with the BIG portrait beside the title and the
    # two landscape illustrations below it, as in the approved preview.
    frame.paste(artwork, (art_x, art_y))
    title = tier.upper() + ' WIN ·'
    baseline = 67 if compact else 64
    draw.text((24, baseline), title, font=font, fill='#fff3e3', anchor='ls')
    draw.text((25, 105), '單局獎金倍率', font=label, fill='#e9d7c8', anchor='ls')
    rgb = frame.tobytes()
    # Store the mostly static artwork as prefiltered PNG scanlines. At runtime
    # only the heading rows need unfiltering to draw the actual multiplier.
    stride = width * 3
    rows = bytearray()
    for y in range(height):
        row = rgb[y * stride:(y + 1) * stride]
        if y <= baseline + 12:
            rows.extend(b'\x00' + row)
        else:
            prev = rgb[(y - 1) * stride:y * stride]
            rows.extend(b'\x02' + bytes((a - b) % 256 for a, b in zip(row, prev)))
    x = 24 + round(font.getlength(title)) + 12
    color = [int(COLORS[tier][i:i + 2], 16) for i in (1, 3, 5)]
    return dict(width=width, height=height, fontSize=font_size, top=baseline - font_size,
                x=x, maxWidth=(art_x if compact else width - 10) - x - 10, color=color, rows=pack(rows))


frames = {record['tier']: build(record) for record in ART}
fonts = {size: masks(ImageFont.truetype(str(FONTS / 'georgiab.ttf'), size), size) for size in (40, 49)}
OUT.write_text(
    '// Generated by scripts/assets/build-discord-win-card.py.\n'
    f'export const frames = {json.dumps(frames, separators=(",", ":"))};\n'
    f'export const fontMasks = {json.dumps(fonts, separators=(",", ":"), ensure_ascii=False)};\n',
    encoding='utf-8',
)
